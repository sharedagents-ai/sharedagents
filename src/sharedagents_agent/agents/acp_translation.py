"""Translation: :data:`AgentTurnEvent` → ACP sessionUpdate.

The :class:`AgentACPBackend.prompt` method yields ACP-shaped dicts.
The :class:`Agent.run_turn` async generator yields
:data:`AgentTurnEvent` instances. This module turns the engine's
events into ACP-wire dicts so the agent side never leaks its own
vocabulary onto the wire.

Source of truth for the ACP wire shape: ``sharedagents_acp/protocol/schema.py``
(autogenerated from ``agentclientprotocol/agent-client-protocol``) plus
the producer-side examples scattered through
``sharedagents_gateway.acp_bridge.CoreBackend.prompt``.

================================================================
Mapping table
================================================================

Forward (engine → ACP), used by :meth:`AgentACPBackend.prompt`:

================================================ ==========================================================
:data:`AgentTurnEvent`                           ACP sessionUpdate
================================================ ==========================================================
``TurnStarted(turn_id, sid, engine_session_id)`` ``-`` (no wire event; captured for cancel routing)
``TextDelta(channel="content", text=…)``         ``agent_message_chunk`` (content type=text)
``TextDelta(channel="thinking", text=…)``        ``agent_thought_chunk`` (visibility gated by cfg)
``TextDelta(channel="tool_delta",                ``tool_call_update`` toolCallId=call_id,
            text=…, call_id=…)``                  content=[{type:text, text}], status="in_progress"
``ToolCallStarted(call_id, name, args,           ``tool_call`` toolCallId, title=name,
                  is_outer=False)``               kind="execute"|"read"|…, status="in_progress",
                                                   rawInput=args
``ToolCallResult(call_id, ok, content)``         ``tool_call_update`` toolCallId, status="completed"|"failed",
                                                   content=[{type:text, text}]
``PermissionRequested(call_id, …, response)``    INTERCEPTED by Agent BEFORE this translator —
                                                   NEVER reaches the wire.
``TurnError(message, classification)``           emits ONE ``agent_message_chunk`` with the error text.
                                                   DOES NOT emit a stopReason — only TurnDone does.
``TurnDone(state="ok", metrics)``                ``usage_update`` (size=ctx_window, used=prompt_tokens,
                                                   _meta.sharedagents.metrics=full), then
                                                   ``stopReason="end_turn"``
``TurnDone(state="aborted")``                    ``stopReason="cancelled"``
``TurnDone(state="error")``                      ``stopReason="end_turn"`` (the TurnError already emitted
                                                   the user-facing message)
================================================ ==========================================================

**Terminal-event contract.**
Exactly ONE ``stopReason`` is emitted per turn, and it ALWAYS comes
from :class:`TurnDone`. :class:`TurnError` carries only the prose
(``agent_message_chunk``). Engines MUST yield a :class:`TurnDone` after
any :class:`TurnError`, even if the only thing TurnDone adds is the
terminal marker. The translator enforces this by tracking whether
a stopReason has been emitted and dropping any duplicate.

Reverse (ACP → engine), used only by :meth:`AgentACPBackend.load_session`
when replaying saved turns from disk:

================================================ ==========================================================
ACP sessionUpdate                                Replay action
================================================ ==========================================================
``agent_message_chunk``                          accumulate into ``content_buf``
``agent_thought_chunk``                          accumulate into ``thinking_buf``
``tool_call``                                    open a synthetic ToolCallStarted with the same call_id
``tool_call_update`` status=in_progress          stream text into the open call's content
``tool_call_update`` status=completed|failed     close with a ToolCallResult
``usage_update``                                 attach as metrics on the turn record
``stopReason``                                   end-of-turn marker
================================================ ==========================================================

The new uniform ``session_log`` schema makes the reverse path cleaner:
each turn record carries structured ``tool_calls[]`` /
``tool_results[]`` so replay no longer parses inline ``🔧 <name>``
markers (the legacy path that lives in
``sharedagents_tui/app.py``'s ``_run_claude`` widget mounting).
"""

from __future__ import annotations

from collections.abc import AsyncIterator, Mapping
from typing import Any

from .engine import (
    AgentTurnEvent,
    PermissionRequested,
    RoundComplete,
    TextDelta,
    ToolCallResult,
    ToolCallStarted,
    TurnDone,
    TurnError,
    TurnStarted,
    UserMessageInjected,
)

# ---- forward (engine → ACP) -----------------------------------------


async def agent_events_to_acp(
    events: AsyncIterator[AgentTurnEvent],
    *,
    context_window: int = 0,
    on_turn_started: Any | None = None,
    on_permission_request: Any | None = None,
) -> AsyncIterator[Mapping[str, Any]]:
    """Stream-translate engine events to ACP sessionUpdate dicts.

    The async-generator shape preserves backpressure: the caller pulls
    one ACP dict at a time, this fn pulls one engine event in response.

    ``on_turn_started`` is an optional callback invoked when the
    initial :class:`TurnStarted` event arrives — used by
    :class:`AgentACPBackend` to record ``sid → turn_id`` for the
    cancel path. The engine
    holds ``turn_id → live subprocess``; the gateway shim resolves
    ACP ``cancel(sid)`` by looking up ``turn_id`` (via the engine's
    ``_session_to_turn`` or the shim's own copy populated here)
    and calling ``engine.abort(turn_id)``.

    ``on_permission_request`` is invoked when a
    :class:`PermissionRequested` event arrives — the Agent layer
    resolves it via its policy/ASK helpers and sets ``ev.response``;
    the translator does NOT forward this to the wire.

    ``context_window`` is the agent's ``cfg.upstream_max_context`` for
    the ``usage_update`` event; CLI-engined agents pass ``0`` and the
    helper omits the size field.

    Terminal-event contract: exactly ONE
    ``stopReason`` is emitted per turn, always from :class:`TurnDone`.
    :class:`TurnError` yields prose only. The translator tracks
    ``stop_reason_emitted`` so a stray duplicate from a buggy engine
    is dropped rather than double-terminating the wire.
    """
    stop_reason_emitted = False

    async for ev in events:
        if isinstance(ev, TurnStarted):
            if on_turn_started is not None:
                try:
                    res = on_turn_started(ev)
                    if hasattr(res, "__await__"):
                        await res
                except Exception:  # noqa: BLE001
                    pass
            # No wire event; turn_id is captured side-channel.
            continue

        if isinstance(ev, PermissionRequested):
            if on_permission_request is not None:
                try:
                    res = on_permission_request(ev)
                    if hasattr(res, "__await__"):
                        await res
                except Exception:  # noqa: BLE001
                    pass
            # Never forwarded to the ACP wire.
            continue

        if isinstance(ev, TextDelta):
            yield text_delta_to_acp(ev)
            continue

        if isinstance(ev, ToolCallStarted):
            if ev.is_outer:
                # Outer wrappers (delegate_* engine call itself) are
                # bookkeeping; the inner tool calls carry the user-
                # visible payload. Skip.
                continue
            yield tool_call_started_to_acp(ev)
            continue

        if isinstance(ev, ToolCallResult):
            yield tool_call_result_to_acp(ev)
            continue

        if isinstance(ev, TurnError):
            for msg in turn_error_to_acp(ev):
                yield msg
            continue

        if isinstance(ev, TurnDone):
            for msg in turn_done_to_acp(ev, context_window=context_window):
                if "stopReason" in msg:
                    if stop_reason_emitted:
                        # Engine bug: TurnDone fired twice. Drop the
                        # duplicate rather than confusing the frontend.
                        continue
                    stop_reason_emitted = True
                yield msg
            continue

        if isinstance(ev, RoundComplete):
            # A tool round finished. The Agent layer forwards this up
            # (after its in-progress persistence checkpoint) carrying
            # the round's worker metrics so we can emit a per-round
            # `usage_update` — this is what makes the frontend's
            # `ctx X/Y` indicator grow after each tool call instead of
            # sitting frozen until `TurnDone`. Rounds without metrics
            # (aborted, CLI engines) translate to nothing.
            for msg in round_complete_to_acp(ev, context_window=context_window):
                yield msg
            continue

        if isinstance(ev, UserMessageInjected):
            # Mid-turn user inject — surface as an ``user_message_chunk``
            # so non-TUI frontends (Telegram, generic ACP clients) can
            # render the steering message above the next assistant
            # round. The TUI mounts its own UserMessage locally on
            # submit so this wire event is a no-op for it (Textual
            # collapses duplicate chunks by content; even if not, the
            # second chunk is informational rather than wrong).
            yield {
                "sessionUpdate": "user_message_chunk",
                "content": {
                    "type": "text",
                    "text": ev.text,
                },
            }
            continue

        # Unknown event variant — surface as a structured note in the
        # stream and keep going. Skeleton-phase safety net.
        yield {
            "sessionUpdate": "agent_message_chunk",
            "content": {
                "type": "text",
                "text": f"[unknown event variant: {type(ev).__name__}]",
            },
        }


def text_delta_to_acp(ev: TextDelta) -> Mapping[str, Any]:
    """One :class:`TextDelta` → one ACP sessionUpdate dict.

    Channel routing:

    * ``"content"``     → ``agent_message_chunk``
    * ``"thinking"``    → ``agent_thought_chunk``
    * ``"tool_delta"``  → ``tool_call_update`` w/ in-progress + content
    """
    channel = ev.channel or "content"
    if channel == "thinking":
        return {
            "sessionUpdate": "agent_thought_chunk",
            "content": {"type": "text", "text": ev.text},
        }
    if channel == "tool_delta":
        return {
            "sessionUpdate": "tool_call_update",
            "toolCallId": ev.call_id,
            "status": "in_progress",
            "content": _tool_call_text_content(ev.text),
        }
    return {
        "sessionUpdate": "agent_message_chunk",
        "content": {"type": "text", "text": ev.text},
    }


def _tool_call_text_content(text: str) -> list[dict[str, Any]]:
    """Wrap a text body as a single ACP-spec ``ToolCallContent`` entry.

    The ACP ``ToolCallContent`` schema is a discriminated union over
    ``{"type": "content"|"diff"|"terminal", ...}``. Earlier emission
    sites passed a raw ``ContentBlock`` (``{"type": "text", "text": ...}``)
    inline — the SDK validator dropped every such update silently,
    so codex / antigravity tool results never rendered in the TUI. Always
    wrap text in the ``content``-typed envelope.

    Kept module-local so the rest of the gateway code can share it
    without an extra import cycle. Mirrors
    ``sharedagents_gateway.acp_bridge._text_tool_content``.
    """
    return [{"type": "content", "content": {"type": "text", "text": text or ""}}]


def _extract_locations(tool_name: str, arguments: Mapping[str, Any]) -> list[dict[str, Any]]:
    """Extract file locations from tool arguments for Zed's clickable navigation."""
    locations = []
    # Most tools use 'file_path'; some use 'path' (like Grep root).
    file_path = arguments.get("file_path") or arguments.get("path")
    if file_path and isinstance(file_path, str):
        # Grep/Glob 'path' is a directory root; skip making it a clickable
        # 'file' location if it's just the current directory.
        if tool_name in {"grep", "glob", "Grep", "Glob"} and file_path in {".", "./"}:
            pass
        else:
            loc: dict[str, Any] = {"uri": f"file://{file_path}", "path": file_path}
            # Some tools use 'offset' or 'line' (1-based).
            line = arguments.get("offset") or arguments.get("line")
            if isinstance(line, (int, float)):
                loc["range"] = {"start": {"line": int(line) - 1, "character": 0}}
            locations.append(loc)
    return locations


def tool_call_started_to_acp(ev: ToolCallStarted) -> Mapping[str, Any]:
    """One :class:`ToolCallStarted` → one ``tool_call`` sessionUpdate."""
    args = dict(ev.arguments or {})
    return {
        "sessionUpdate": "tool_call",
        "toolCallId": ev.call_id,
        "title": ev.name,
        "kind": acp_kind_for_tool(ev.name),
        "status": "in_progress",
        "rawInput": args,
        "locations": _extract_locations(ev.name, args),
    }


def tool_call_result_to_acp(ev: ToolCallResult) -> Mapping[str, Any]:
    """One :class:`ToolCallResult` → one ``tool_call_update``."""
    return {
        "sessionUpdate": "tool_call_update",
        "toolCallId": ev.call_id,
        "status": "completed" if ev.ok else "failed",
        "content": _tool_call_text_content(ev.content or ""),
    }


def turn_error_to_acp(ev: TurnError) -> list[Mapping[str, Any]]:
    """One :class:`TurnError` → ``[agent_message_chunk]`` only.

    TurnError does NOT emit ``stopReason``.
    Only :class:`TurnDone` terminates a turn. The engine MUST yield
    a TurnDone after any TurnError (even if only to convey the
    terminal marker).
    """
    return [
        {
            "sessionUpdate": "agent_message_chunk",
            "content": {"type": "text", "text": ev.message or ""},
        }
    ]


def _usage_update_from_metrics(metrics: Mapping[str, Any], *, context_window: int = 0) -> Mapping[str, Any] | None:
    """Build a single ``usage_update`` dict from a metrics mapping.

    Returns ``None`` when ``metrics`` carries no ``prompt_tokens`` (CLI
    engines, aborted rounds) so callers can skip the event entirely.

    ``used`` = this round's ``prompt_tokens`` (the live context size);
    ``size`` = the context window (denominator), clamped to never read
    below ``used``. The full metrics ride along in
    ``_meta.sharedagents.metrics`` so the TUI footer can stamp the rich
    per-round stats line AND refresh both halves of ``ctx X/Y``.
    """
    pt = metrics.get("prompt_tokens")
    if pt is None:
        return None
    used = int(pt or 0)
    # An engine that knows its own window (e.g. an ACP engine reporting
    # the model's real context size) carries it in ``metrics`` — prefer
    # that over the agent-wide ``context_window`` default so the ctx
    # denominator is correct per-model.
    size = int(metrics.get("context_window") or context_window or used)
    # Include context_window in the tunneled metrics so the TUI can
    # update `_last_context_window` from every per-round `usage_update`
    # event — without this the footer's `ctx X/Y` segment can't refresh
    # its Y component turn-by-turn.
    enriched = dict(metrics)
    if not enriched.get("context_window"):
        enriched["context_window"] = max(size, used)
    return {
        "sessionUpdate": "usage_update",
        "size": max(size, used),
        "used": used,
        "_meta": {"sharedagents": {"metrics": enriched}},
    }


def round_complete_to_acp(ev: RoundComplete, *, context_window: int = 0) -> list[Mapping[str, Any]]:
    """One :class:`RoundComplete` → ``[usage_update?]`` (NO stopReason).

    Emits a per-round ``usage_update`` so the frontend's ``ctx X/Y``
    indicator climbs after every tool round — the engine produces a
    fresh, growing ``prompt_tokens`` each round (the ``TURN_METRICS
    round=N`` lines), and without this the footer sat frozen on the
    health-probe baseline for the entire multi-round turn. A round is
    NOT terminal, so this never carries a ``stopReason``; only
    :func:`turn_done_to_acp` terminates the turn.
    """
    usage = _usage_update_from_metrics(ev.metrics or {}, context_window=context_window)
    return [usage] if usage is not None else []


def turn_done_to_acp(ev: TurnDone, *, context_window: int = 0) -> list[Mapping[str, Any]]:
    """One :class:`TurnDone` → ``[usage_update?, stopReason]``.

    ``usage_update`` is only emitted when ``ev.metrics`` carries
    ``prompt_tokens`` (LLM engines do; CLI engines typically don't,
    so the helper omits it for them).

    ``stopReason`` mapping:

    * state="ok"       → "end_turn"
    * state="error"    → "end_turn" (the TurnError already conveyed
                          the user-facing message)
    * state="aborted"  → "cancelled"
    """
    out: list[Mapping[str, Any]] = []
    usage = _usage_update_from_metrics(ev.metrics or {}, context_window=context_window)
    if usage is not None:
        out.append(usage)

    # An engine/upstream error must be distinguishable on
    # the wire from genuine success WITHOUT replaying the message stream for a
    # TurnError chunk. ``refusal`` is a standard ACP stop reason (already used
    # for a queue-full rejection at acp_bridge.py) — reusing it costs no new
    # wire vocabulary while separating error from the ``end_turn`` of success.
    reason_map = {
        "ok": "end_turn",
        "error": "refusal",
        "aborted": "cancelled",
    }
    out.append(
        {
            "stopReason": reason_map.get(ev.state, "end_turn"),
        }
    )
    return out


# A reverse translator (``acp_sessionupdates_to_agent_events``) was
# intentionally NOT implemented: under the post-cutover architecture
# the agent stream flows in only one direction —
# ``Agent.run_turn`` yields :data:`AgentTurnEvent` instances which
# this module turns into ACP ``sessionUpdate`` dicts at the wire
# layer. Nothing consumes the inverse direction, so the prior
# placeholder was deleted.


# ---- per-channel kind classification --------------------------------


def acp_kind_for_tool(tool_name: str) -> str:
    """Map a sharedagents tool name to an ACP ``tool_call.kind`` value.

    ACP defines: ``read`` / ``edit`` / ``execute`` / ``search`` /
    ``other``. Today the gateway emits ``"execute"`` for everything;
    we improve here so the frontend can render distinct widget styles
    (read = grey, edit = orange, execute = red border).

    Mapping (per ``sharedagents_agent.tools.registry``). The web /
    memory recall tools are MCP tools now, so match their namespaced names.

    * Read, Glob, Grep, monitor_list,
      mcp__web__fetch, mcp__web__search,
      mcp__memory__get                        → ``read``
    * Write, Edit, Update, MultiEdit,
      NotebookEdit                            → ``edit``
    * Bash, Monitor, BashOutput, KillShell         → ``execute``
    * tool_search, mcp_list_tools,
      Skill, remember, memory_search,
      mcp__memory__session_search             → ``search``
    * Everything else (delegate, task, etc)   → ``other``
    """
    if not tool_name:
        return "other"
    if tool_name in {
        "read",
        "Read",
        "glob",
        "Glob",
        "grep",
        "Grep",
        "list",
        "monitor_list",
        "mcp__web__fetch",
        "mcp__web__search",
        "mcp__memory__search",
        "mcp__memory__get",
    }:
        return "read"
    if tool_name in {"write", "edit", "Write", "Edit", "Update", "MultiEdit", "NotebookEdit"}:
        return "edit"
    if tool_name in {"bash", "Bash", "Monitor", "BashOutput", "KillShell"}:
        return "execute"
    if tool_name in {
        "tool_search",
        "mcp_list_tools",
        "Skill",
        "SkillSearch",  # legacy name; tool removed, keep for old transcripts
        "remember",
        "memory_search",
        "mcp__memory__session_search",
        "mcp__memory__remember",
    }:
        return "search"
    return "other"
